#!/bin/zsh
# zsh is required: this is a macOS installer/build script. Google Shell
# Style permits a non-bash interpreter when the execution environment
# forces it (https://google.github.io/styleguide/shellguide.html).
# Emit cdhashes.h from the two decoder bundles. Run this whenever a plugin is rebuilt:
# the kext allowlist is keyed on the executable cdhash, which changes if the Mach-O changes.
set -e
cd "${0:A:h}"
AV1=../vtav1/build/AV1VCNDecoder.bundle
VP9=../vtvp9/build/VP9VCNDecoder.bundle
cdhash() {  # full sha256 cdhash (64 hex), lowercased, as a C byte array
  codesign -dvvv "$1" 2>&1 | awk -F= '/CandidateCDHashFull sha256/{print $2}' | tr -d ' \n'
}
hex_to_c() { echo "$1" | sed -E 's/(..)/0x\1, /g'; }
A=$(cdhash "${AV1}"); V=$(cdhash "${VP9}")
[[ ${#A} -ge 40 && ${#V} -ge 40 ]] || { echo "could not read cdhashes"; exit 1; }
cat > cdhashes.h <<EOF
// Generated by gen_cdhashes.sh — do not edit by hand. Regenerate after rebuilding a plugin.
#ifndef VCNVTKEXT_CDHASHES_H_
#define VCNVTKEXT_CDHASHES_H_

#include <stddef.h>
#include <stdint.h>
// AV1VCNDecoder (com.droga.videodecoder.av1.vcn)
static const uint8_t kCdhashAV1[] = { $(hex_to_c "${A}") };
// VP9VCNDecoder (com.droga.videodecoder.vp9.vcn)
static const uint8_t kCdhashVP9[] = { $(hex_to_c "${V}") };
static const uint8_t *kAllowedCdhashes[] = { kCdhashAV1, kCdhashVP9 };
static const size_t kAllowedCdhashLen = 32; // sha256 cdhash, full length
static const size_t kAllowedCdhashCount = 2;

#endif  // VCNVTKEXT_CDHASHES_H_
EOF
echo "wrote cdhashes.h  (AV1=${A:0:16}…  VP9=${V:0:16}…)"
